"""Static write-capability audit engine for controller code (Phase 9A).

Inspects Python modules in controller/ and PowerShell scripts in scripts/controller/
to verify that no write-capable Kubernetes calls, scale mutations, or Kubernetes
client imports exist in the observe-only codebase.
"""

import ast
import re
from dataclasses import dataclass, field
from pathlib import Path

FORBIDDEN_PYTHON_IMPORTS: set[str] = {
    "kubernetes",
    "kubernetes.client",
    "kubernetes.config",
}

FORBIDDEN_METHOD_CALLS: set[str] = {
    "patch_namespaced_deployment_scale",
    "replace_namespaced_deployment_scale",
    "patch_namespaced_deployment",
    "replace_namespaced_deployment",
    "create_namespaced_deployment",
    "delete_namespaced_deployment",
}

FORBIDDEN_CALL_VERBS: set[str] = {
    "scale",
    "patch",
    "apply",
}

FORBIDDEN_KUBECTL_VERBS: list[re.Pattern[str]] = [
    re.compile(r"\bkubectl\s+(apply|scale|patch|delete)\b", re.IGNORECASE),
]


@dataclass
class AuditViolation:
    """A violation discovered during static write-capability audit."""

    file_path: str
    line_number: int
    rule: str
    code_snippet: str
    explanation: str


@dataclass
class WriteCapabilityAuditReport:
    """Report generated by static write-capability audit."""

    passed: bool
    files_scanned: list[str] = field(default_factory=list)
    violations: list[AuditViolation] = field(default_factory=list)


class _WriteCallVisitor(ast.NodeVisitor):
    """AST visitor scanning for forbidden imports and write calls."""

    def __init__(self, file_path: str, source_lines: list[str]) -> None:
        self.file_path = file_path
        self.source_lines = source_lines
        self.violations: list[AuditViolation] = []

    def visit_Import(self, node: ast.Import) -> None:  # noqa: N802
        for alias in node.names:
            base_mod = alias.name.split(".")[0]
            if alias.name in FORBIDDEN_PYTHON_IMPORTS or base_mod == "kubernetes":
                self._record_violation(
                    node.lineno,
                    "FORBIDDEN_K8S_IMPORT",
                    f"Importing '{alias.name}' is forbidden in observe-only controller runtime",
                )
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:  # noqa: N802
        if node.module:
            base_mod = node.module.split(".")[0]
            if node.module in FORBIDDEN_PYTHON_IMPORTS or base_mod == "kubernetes":
                self._record_violation(
                    node.lineno,
                    "FORBIDDEN_K8S_IMPORT",
                    f"Importing from '{node.module}' is forbidden in observe-only controller runtime",
                )
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:  # noqa: N802
        # Check call method name
        func_name = ""
        if isinstance(node.func, ast.Attribute):
            func_name = node.func.attr
        elif isinstance(node.func, ast.Name):
            func_name = node.func.id

        if func_name in FORBIDDEN_METHOD_CALLS:
            self._record_violation(
                node.lineno,
                "FORBIDDEN_WRITE_CALL",
                f"Calling write method '{func_name}' is forbidden in observe-only controller",
            )
        elif func_name.lower() in FORBIDDEN_CALL_VERBS and isinstance(node.func, ast.Attribute):
            # Flag obj.scale(...) or obj.patch(...)
            self._record_violation(
                node.lineno,
                "SUSPICIOUS_WRITE_VERB",
                f"Invoking '{func_name}' method is forbidden in observe-only controller",
            )

        self.generic_visit(node)

    def _record_violation(self, lineno: int, rule: str, explanation: str) -> None:
        snippet = self.source_lines[lineno - 1].strip() if 0 < lineno <= len(self.source_lines) else ""
        self.violations.append(
            AuditViolation(
                file_path=self.file_path,
                line_number=lineno,
                rule=rule,
                code_snippet=snippet,
                explanation=explanation,
            )
        )


def audit_python_file(path: Path) -> list[AuditViolation]:
    """Audit a single Python file using AST analysis."""
    # Exclude audit.py itself from self-flagging strings
    if path.name == "audit.py":
        return []

    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    try:
        tree = ast.parse(text, filename=str(path))
    except SyntaxError as e:
        return [
            AuditViolation(
                file_path=str(path),
                line_number=e.lineno or 1,
                rule="SYNTAX_ERROR",
                code_snippet="",
                explanation=f"Failed to parse AST: {e}",
            )
        ]

    visitor = _WriteCallVisitor(str(path), lines)
    visitor.visit(tree)
    return visitor.violations


def audit_powershell_file(path: Path) -> list[AuditViolation]:
    """Audit a PowerShell script for forbidden write-capable kubectl invocations."""
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    violations: list[AuditViolation] = []

    for i, line in enumerate(lines, start=1):
        stripped = line.strip()
        # Ignore comment lines
        if stripped.startswith("#") or stripped.startswith("<#"):
            continue
        for pattern in FORBIDDEN_KUBECTL_VERBS:
            match = pattern.search(line)
            if match:
                violations.append(
                    AuditViolation(
                        file_path=str(path),
                        line_number=i,
                        rule="FORBIDDEN_KUBECTL_WRITE",
                        code_snippet=stripped,
                        explanation=f"Found write-capable command '{match.group(0)}' in controller script",
                    )
                )

    return violations


def run_write_capability_audit(
    controller_dir: Path | None = None,
    scripts_dir: Path | None = None,
) -> WriteCapabilityAuditReport:
    """Execute complete write-capability audit across controller Python and script files."""
    repo_root = Path(__file__).resolve().parent.parent
    c_dir = controller_dir if controller_dir is not None else repo_root / "controller"
    s_dir = scripts_dir if scripts_dir is not None else repo_root / "scripts" / "controller"

    files_scanned: list[str] = []
    all_violations: list[AuditViolation] = []

    if c_dir.exists():
        for py_file in sorted(c_dir.glob("**/*.py")):
            files_scanned.append(str(py_file))
            v = audit_python_file(py_file)
            all_violations.extend(v)

    if s_dir.exists():
        for ps_file in sorted(s_dir.glob("**/*.ps1")):
            files_scanned.append(str(ps_file))
            v = audit_powershell_file(ps_file)
            all_violations.extend(v)

    passed = len(all_violations) == 0
    return WriteCapabilityAuditReport(
        passed=passed,
        files_scanned=files_scanned,
        violations=all_violations,
    )
