"""Controller operational metrics and isolated Prometheus metrics server (Phase 9A)."""

import logging
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer
from typing import Any

from prometheus_client import CollectorRegistry, Counter, Gauge, generate_latest

logger = logging.getLogger(__name__)

ALLOWED_OUTCOMES: set[str] = {
    "forecast_created",
    "forecast_skipped_insufficient_history",
    "forecast_skipped_stale_telemetry",
    "forecast_skipped_unavailable",
    "actual_matched",
    "pending_actual",
}


class ObserverMetrics:
    """Manages operational metrics for KubePredict observe-only controller."""

    def __init__(self, registry: CollectorRegistry | None = None) -> None:
        self.registry = registry if registry is not None else CollectorRegistry(auto_describe=True)

        self.cycles_total = Counter(
            "kubepredict_observer_cycles_total",
            "Total number of controller observation cycles executed",
            ["outcome"],
            registry=self.registry,
        )

        self.telemetry_age_seconds = Gauge(
            "kubepredict_observer_telemetry_age_seconds",
            "Age of latest telemetry observation in seconds",
            registry=self.registry,
        )

        self.history_observations = Gauge(
            "kubepredict_observer_history_observations",
            "Count of valid observations available in current history window",
            registry=self.registry,
        )

        self.forecasts_total = Counter(
            "kubepredict_observer_forecasts_total",
            "Total number of forecasts generated by the controller",
            ["model", "fallback_used"],
            registry=self.registry,
        )

        self.prediction_request_rate = Gauge(
            "kubepredict_observer_prediction_request_rate",
            "Most recent predicted request rate per second",
            registry=self.registry,
        )

        self.actual_request_rate = Gauge(
            "kubepredict_observer_actual_request_rate",
            "Most recent matched actual request rate per second",
            registry=self.registry,
        )

        self.absolute_error = Gauge(
            "kubepredict_observer_absolute_error",
            "Most recent matched forecast absolute error",
            registry=self.registry,
        )

        self.pending_forecasts = Gauge(
            "kubepredict_observer_pending_forecasts",
            "Number of forecasts currently awaiting actual observations",
            registry=self.registry,
        )

        self.matched_forecasts_total = Counter(
            "kubepredict_observer_matched_forecasts_total",
            "Total number of forecasts successfully matched against actuals",
            registry=self.registry,
        )

        self.expired_forecasts_total = Counter(
            "kubepredict_observer_expired_forecasts_total",
            "Total number of pending forecasts that expired without match",
            registry=self.registry,
        )

    def record_cycle(
        self,
        outcome: str,
        telemetry_age: float,
        obs_count: int,
        pending_count: int,
    ) -> None:
        """Record base cycle metrics."""
        safe_outcome = outcome if outcome in ALLOWED_OUTCOMES else "unknown"
        self.cycles_total.labels(outcome=safe_outcome).inc()
        if telemetry_age < 1e9:  # Avoid infinite age on gauge
            self.telemetry_age_seconds.set(telemetry_age)
        self.history_observations.set(obs_count)
        self.pending_forecasts.set(pending_count)

    def record_forecast(
        self,
        model_name: str,
        fallback_used: bool,
        predicted_val: float,
    ) -> None:
        """Record forecast generation."""
        fb_str = "true" if fallback_used else "false"
        self.forecasts_total.labels(model=model_name, fallback_used=fb_str).inc()
        self.prediction_request_rate.set(predicted_val)

    def record_matched(
        self,
        actual_val: float,
        abs_err: float,
    ) -> None:
        """Record matched actual outcome and error."""
        self.matched_forecasts_total.inc()
        self.actual_request_rate.set(actual_val)
        self.absolute_error.set(abs_err)

    def record_expired(self, count: int = 1) -> None:
        """Record expired forecasts."""
        self.expired_forecasts_total.inc(count)


class _MetricsHandler(BaseHTTPRequestHandler):
    """HTTP handler exposing Prometheus metrics from the isolated registry."""

    registry: CollectorRegistry

    def do_GET(self) -> None:  # noqa: N802
        if self.path in ("/metrics", "/metrics/"):
            output = generate_latest(self.registry)
            self.send_response(200)
            self.send_header("Content-Type", "text/plain; version=0.0.4; charset=utf-8")
            self.send_header("Content-Length", str(len(output)))
            self.end_headers()
            self.wfile.write(output)
        elif self.path in ("/", "/healthz"):
            self.send_response(200)
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.end_headers()
            self.wfile.write(b"OK\n")
        else:
            self.send_response(404)
            self.end_headers()

    def log_message(self, format: str, *args: Any) -> None:
        # Suppress noisy HTTP request logs
        pass


class MetricsServer:
    """Threaded local metrics server for KubePredict controller observer."""

    def __init__(
        self,
        host: str = "127.0.0.1",
        port: int = 9101,
        registry: CollectorRegistry | None = None,
    ) -> None:
        self.host = host
        self.port = port
        self.registry = registry if registry is not None else CollectorRegistry(auto_describe=True)
        self._server: HTTPServer | None = None
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        """Start the metrics HTTP server in a daemon thread."""
        handler_class = type(
            "BoundMetricsHandler",
            (_MetricsHandler,),
            {"registry": self.registry},
        )
        self._server = HTTPServer((self.host, self.port), handler_class)
        self._thread = threading.Thread(target=self._server.serve_forever, daemon=True)
        self._thread.start()
        logger.info("Metrics server listening on http://%s:%d/metrics", self.host, self.port)

    def stop(self) -> None:
        """Shut down the HTTP server and release the port."""
        if self._server is not None:
            self._server.shutdown()
            self._server.server_close()
            self._server = None
        if self._thread is not None:
            self._thread.join(timeout=2.0)
            self._thread = None
        logger.info("Metrics server stopped.")
